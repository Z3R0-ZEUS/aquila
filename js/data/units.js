export function typeOf(unit) {
  return UNIT_TYPES[unit.typeId];
}

let _id = 1;
export function resetUnitIds(n = 1) {
  _id = n;
}

export function makeUnit(typeId, extras = {}) {
  const t = UNIT_TYPES[typeId];
  if (!t) throw new Error(`Unknown unit type ${typeId}`);
  return {
    id: extras.id || `u${_id++}`,
    typeId,
    faction: t.faction,
    name: extras.name || t.name,
    q: extras.q ?? 0,
    r: extras.r ?? 0,
    strength: extras.strength ?? t.maxStrength,
    maxStrength: extras.maxStrength ?? t.maxStrength,
    disorder: extras.disorder ?? 0,
    entrench: extras.entrench ?? 0,
    experience: extras.experience ?? 0,
    ammo: extras.ammo ?? t.ammo,
    moved: false,
    acted: false,
    mpRemaining: t.move,
    hidden: extras.hidden ?? t.traits.includes('hiddenStart'),
    chargedThisTurn: extras.chargedThisTurn ?? false,
    core: extras.core ?? false,
    facing: extras.facing ?? 1,
    upgrades: extras.upgrades ? { ...extras.upgrades } : {},
    testudo: extras.testudo ?? false,
    forcedMarch: extras.forcedMarch ?? false,
    hiredThisBattle: extras.hiredThisBattle ?? false,
    extracted: extras.extracted ?? false,
    inSupply: extras.inSupply ?? true,
  };
}

export function effectiveStrength(unit) {
  return Math.max(0, unit.strength - unit.disorder);
}

export function isHero(unit) {
  return typeOf(unit).traits.includes('hero');
}

export function upgradeKindOf(typeOrUnit) {
  const t = typeOrUnit?.traits ? typeOrUnit : typeOf(typeOrUnit);
  if (!t) return 'armor';
  if (t.traits.includes('cavalry')) return 'charge';
  if (t.traits.includes('missile')) return 'missile';
  if (t.traits.includes('engineer')) return 'ward';
  return 'armor';
}
