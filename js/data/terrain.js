export function moveCost(terrain, unitType, weather) {
  const t = TERRAIN[terrain];
  if (!t || t.impassable) return Infinity;
  if (t.blockCavalry && unitType.traits.includes('cavalry')) return Infinity;
  let cost = t.cavalryMove && unitType.traits.includes('cavalry') ? t.cavalryMove : t.move;
  if (weather === 'rain' && terrain !== 'causeway' && terrain !== 'castra' && terrain !== 'road') {
    cost += 1;
  }
  if (unitType.traits.includes('forestFighter') && (terrain === 'lightForest' || terrain === 'denseForest')) {
    cost = Math.max(1, cost - 1);
  }
  return cost;
}
